import fs from "fs";
import path from "path";
import {
	PLACEHOLDERS,
	placeholdersIn,
} from "../src/domain/init/fill-template.js";

export const TEMPLATES = path.resolve("templates");
export const OUTPUT = path.resolve("src/domain/init/starter-templates.ts");

const PLACES_SUFFIX = "-places";

/** The folder of the Greeter feature, wherever a variant puts it. */
const FEATURE = "/Greeter/";

function listed(dir: string, prefix = ""): string[] {
	return fs
		.readdirSync(dir, { withFileTypes: true })
		.flatMap((entry) =>
			entry.isDirectory()
				? listed(path.join(dir, entry.name), `${prefix}${entry.name}/`)
				: [`${prefix}${entry.name}`]
		);
}

/** Every file below `templates/` but its README, by path, read as LF whatever git checked out. */
export function readTemplates(dir: string): Record<string, string> {
	return Object.fromEntries(
		listed(dir)
			.filter((file) => file !== "README.md")
			.sort()
			.map((file) => [
				file,
				fs
					.readFileSync(path.join(dir, file), "utf8")
					.replace(/\r\n/g, "\n"),
			])
	);
}

function featureOf(
	files: Readonly<Record<string, string>>,
	variant: string
): Record<string, string> {
	const prefix = `${variant}/`;
	return Object.fromEntries(
		Object.entries(files)
			.filter(([file]) => file.startsWith(prefix))
			.flatMap(([file, content]) => {
				const at = file.indexOf(FEATURE, prefix.length);
				return at < 0
					? []
					: [[file.slice(at + FEATURE.length), content]];
			})
	);
}

function checkPlaceholders(files: Readonly<Record<string, string>>): void {
	for (const [file, content] of Object.entries(files))
		for (const name of placeholdersIn(content))
			if (!(PLACEHOLDERS as readonly string[]).includes(name))
				throw new Error(
					`templates/${file} uses {{${name}}}, which init doesn't fill. It fills ${PLACEHOLDERS.join(", ")}.`
				);
}

function checkFeatures(files: Readonly<Record<string, string>>): void {
	const variants = new Set(
		Object.keys(files)
			.filter((file) => file.includes("/"))
			.map((file) => file.split("/")[0])
	);
	for (const several of variants) {
		if (!several.endsWith(PLACES_SUFFIX)) continue;
		const single = several.slice(0, -PLACES_SUFFIX.length);
		if (
			JSON.stringify(featureOf(files, single)) !==
			JSON.stringify(featureOf(files, several))
		)
			throw new Error(
				`The Greeter feature of ${single} and ${several} must be the same.`
			);
	}
}

/** The files as the module that embeds them holds them. */
export function renderTemplatesModule(
	files: Readonly<Record<string, string>>
): string {
	checkPlaceholders(files);
	checkFeatures(files);
	const entries = Object.entries(files).map(
		([file, content]) =>
			`\t${JSON.stringify(file)}: ${JSON.stringify(content)},\n`
	);
	return `// Generated by scripts/generate-templates.ts. Do not edit.
/** The files \`init\` writes a project from, by path below \`templates/\`. */
export const starterTemplates: Readonly<Record<string, string>> = {
${entries.join("")}};
`;
}

export function currentTemplatesModule(): string {
	return renderTemplatesModule(readTemplates(TEMPLATES));
}
