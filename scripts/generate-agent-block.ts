import fs from "fs";
import path from "path";

const RULES = path.resolve("skills/rogen/agent-rules.md");
export const OUTPUT = path.resolve("src/domain/init/agent/agent-block.ts");

/** The agent rules with their markers, as the module that embeds it holds it. */
export function renderAgentBlockModule(rules: string): string {
	const block = /<!-- rogen -->\n[\s\S]*?\n<!-- \/rogen -->/.exec(
		rules.replace(/\r\n/g, "\n")
	)?.[0];
	if (!block) throw new Error("The agent rules have no <!-- rogen --> block.");
	return `// Generated by scripts/generate-agent-block.ts. Do not edit.
/** Rogen's rules for coding agents, between the markers that tell \`init\` the block is already there. */
export const agentBlock = ${JSON.stringify(`${block}\n`)};
`;
}

export function currentAgentBlockModule(): string {
	return renderAgentBlockModule(fs.readFileSync(RULES, "utf8"));
}
