import { PlannedFile } from "../toolchain/toolchain.js";
import { InitKind } from "./init-service.js";

export const HOMEPAGE = "https://rogen-playfully.vercel.app/";

const ROBLOX_LOCKS =
	"# Roblox Studio lock files\n/*.rbxlx.lock\n/*.rbxl.lock\n";

/** The files `rojo init --kind` writes beside the project file, where none exists: Rojo's own contents, with Rogen's commands in the README. */
export class ProjectTemplate {
	constructor(
		readonly kind: InitKind,
		/** The project's name, which Rojo takes from the folder. */
		readonly name: string
	) {}

	get readme(): PlannedFile {
		const { name } = this;
		const intro = `# ${name}\nGenerated by [Rogen](${HOMEPAGE}).\n\n## Getting Started\n`;
		const outro =
			"\nFor more help, check out [the Rogen documentation](" +
			HOMEPAGE +
			").\n";
		const block = (...lines: string[]) =>
			`\`\`\`bash\n${lines.join("\n")}\n\`\`\`\n`;
		const body =
			this.kind === "place"
				? `To build the place from scratch, use:\n\n${block(`rogen build -o "${name}.rbxlx"`)}\nNext, open \`${name}.rbxlx\` in Roblox Studio and start the Rojo server:\n\n${block("rogen serve")}`
				: this.kind === "model"
					? `To build this library, use:\n\n${block(`rogen build -o "${name}.rbxmx"`)}`
					: `To build this plugin to your local plugins folder, use:\n\n${block(`rogen build -p "${name}.rbxm"`)}\nYou can include the \`watch\` flag to re-build it on save:\n\n${block(`rogen build -p "${name}.rbxm" --watch`)}`;
		return { fileName: "README.md", content: `${intro}${body}${outro}` };
	}

	get gitignore(): PlannedFile {
		const { name } = this;
		const project =
			this.kind === "place"
				? `# Project place file\n/${name}.rbxlx\n\n${ROBLOX_LOCKS}`
				: this.kind === "plugin"
					? `# Plugin model files\n/${name}.rbxmx\n/${name}.rbxm\n`
					: ROBLOX_LOCKS;
		return {
			fileName: ".gitignore",
			content: `${project}\nsourcemap.json\n`,
		};
	}

	/** The one script of a model or a plugin, which the project mounts as `src`; a place's code is its routes'. */
	get script(): PlannedFile | undefined {
		switch (this.kind) {
			case "model":
				return {
					fileName: "src/init.luau",
					content: `return {\n\thello = function()\n\t\tprint("Hello world, from ${this.name}!")\n\tend,\n}\n`,
				};
			case "plugin":
				return {
					fileName: "src/init.server.luau",
					content: 'print("Hello world, from plugin!")\n',
				};
			case "place":
				return undefined;
		}
	}
}
